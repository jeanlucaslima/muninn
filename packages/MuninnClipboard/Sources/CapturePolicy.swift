import Foundation
import MuninnCore

/// Which representations to read for one observed change (design §4.3,
/// §4.8). Pure: decides from the offered type identifiers alone, before
/// anything is read.
public enum CapturePolicy {
    public enum ReadKind: Sendable, Equatable {
        /// Read as a string.
        case text
        /// Read as bytes.
        case data
        /// Read every file URL on the pasteboard.
        case fileURLs
    }

    public struct PlannedRead: Sendable, Equatable {
        public let uti: String
        public let role: RepresentationRole
        public let kind: ReadKind
    }

    public enum Plan: Sendable, Equatable {
        /// Concealed, transient or auto-generated content: read nothing,
        /// count nothing (invariant 4).
        case skipPrivacy
        /// Muninn's own write; carries the item id if the marker had one.
        case selfCopy
        /// Read these, primary first.
        case read([PlannedRead])
        /// Nothing Muninn keeps was offered (e.g. only app-private types).
        case nothingToKeep
    }

    public static let privacyTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    public static let sourceType = "org.nspasteboard.source"

    static let plainText = "public.utf8-plain-text"
    static let html = "public.html"
    static let rtf = "public.rtf"
    static let pdf = "com.adobe.pdf"
    static let fileURL = "public.file-url"
    /// Compact rasters, in preference order; only the first offered is kept.
    static let compactRasters = ["public.png", "public.jpeg", "public.heic"]
    static let tiff = "public.tiff"

    public static func plan(offeredTypes: [String]) -> Plan {
        let offered = Set(offeredTypes)
        if !offered.isDisjoint(with: privacyTypes) {
            return .skipPrivacy
        }
        if offered.contains(MuninnPaths.selfCopyMarkerType) {
            return .selfCopy
        }
        // Finder copies: keep the references; the names, icons and text
        // Finder also offers are derived from them.
        if offered.contains(fileURL) {
            return .read([PlannedRead(uti: fileURL, role: .primary, kind: .fileURLs)])
        }

        var reads: [PlannedRead] = []
        func add(_ uti: String, _ kind: ReadKind) {
            if offered.contains(uti) { reads.append(PlannedRead(uti: uti, role: .alternate, kind: kind)) }
        }
        add(plainText, .text)
        add(rtf, .data)
        add(html, .text)
        add(pdf, .data)
        // Don't read TIFF when a compact raster type is offered (§4.3).
        if let raster = compactRasters.first(where: offered.contains) {
            add(raster, .data)
        } else {
            add(tiff, .data)
        }

        guard let first = reads.first else { return .nothingToKeep }
        // Primary: plain text when present (text identity, §4.3), otherwise the
        // richest content in the order above.
        reads[0] = PlannedRead(uti: first.uti, role: .primary, kind: first.kind)
        return .read(reads)
    }
}
